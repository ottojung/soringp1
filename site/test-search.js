/* Dependency-free functional tests against the actual generated search index. */
"use strict";
const assert=require("node:assert/strict");
const fs=require("node:fs");
const path=require("node:path");
const search=require("./assets/search-core.js");
const root=path.join(__dirname,"_site","search");
const read=name=>JSON.parse(fs.readFileSync(path.join(root,name+".json"),"utf8"));
const manifest=read("manifest"), records=read("records"), cache=new Map();
const shard=async name=>{if(!cache.has(name))cache.set(name,read(name));return cache.get(name);};
const filter={kind:"",topic:"",status:"",sort:"relevance"};
(async()=>{
  assert.deepEqual(search.intersection([1,3,5],[2,3,5,7]),[3,5]);
  assert.deepEqual(search.union([[1,3],[2,3]]),[1,2,3]);
  assert.deepEqual(search.tokenize("The F(P), M1 and M2",manifest),["f","p","m1","m2"]);
  const all=await search.find(records,manifest,"",filter,shard);
  assert.equal(all.ids.length,records.length);
  const cos=await search.find(records,manifest,"cospectral minimax",{...filter,kind:"front"},shard);
  assert(cos.ids.some(i=>records[i].title==="cospectral-gap-span-alln"));
  assert(cos.ids.every(i=>records[i].kind==="front"));
  const direct=await search.find(records,manifest,"cospectral-gap-span-alln",{...filter,kind:"front"},shard);
  assert.equal(records[direct.ids[0]].title,"cospectral-gap-span-alln");
  const topic=records[direct.ids[0]].topics[0];
  const related=await search.find(records,manifest,"cospectral",{...filter,topic},shard);
  assert(related.ids.length>0 && related.ids.every(i=>records[i].topics.includes(topic)));
  const formal=await search.find(records,manifest,"",{...filter,evidence:"formal"},shard);
  assert.equal(formal.ids.length,2);
  assert(formal.ids.every(i=>records[i].kind==="result"));
  const conditional=await search.find(records,manifest,"policy",{...filter,evidence:"conditional"},shard);
  assert(conditional.ids.some(i=>records[i].id==="C05"));
  const blocked=await search.find(records,manifest,"",{...filter,status:"blocked"},shard);
  assert.equal(blocked.ids.length,33);
  const review=await search.find(records,manifest,"",{...filter,kind:"board",status:"review",sort:"newest"},shard);
  assert(review.ids.length>0 && review.ids.every(i=>records[i].status==="review"));
  const no=await search.find(records,manifest,"zzzzneverexistsinarchive9876",filter,shard);
  assert.equal(no.ids.length,0);
  const empty=await search.find(records,manifest,"",{...filter,kind:"scratch"},shard);
  assert.equal(empty.ids.length,570);
  console.log("Search functional tests passed: full index, exact front, multiword, topic, workflow status, newest review, zero results, scratch coverage.");
})().catch(err=>{console.error(err);process.exitCode=1;});
