#!/usr/bin/env python3
"""Interval-module reversal quotient: exact canonical form and evaluation cost.

UNTracked research script.  Companion to docs/research-orientation-modules.md,
Theorem 3: if S is an interval module of P (every outside key is comparable to
every member of S) then reversing the internal order of S preserves F exactly.

We build the equivalence generated by
    (i)  relabelling of the n keys, and
    (ii) reversal of every interval module S (including S = V, the order dual),
on isomorphism classes of posets.  The quotient is sound for F: relabelling is
an order isomorphism, and each interval reversal preserves F by Theorem 3.
No generator is omitted and no orbit is pruned by an unproved criterion.

At n = 7 we check F is constant on every produced class, using the exact
iso-class DP (2045 classes).  We then compare exact evaluation work for S(7)
and, subject to a wall-clock cap, S(8).
"""

import argparse
