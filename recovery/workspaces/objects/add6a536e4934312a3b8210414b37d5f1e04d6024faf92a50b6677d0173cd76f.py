KNOWN = {0: 0, 1: 0, 2: 1, 3: 3, 4: 5, 5: 7, 6: 10, 7: 13, 8: 16}
A000112 = {0: 1, 1: 1, 2: 2, 3: 5, 4: 16, 5: 63, 6: 318, 7: 2045, 8: 16999}


# --------------------------------------------------------------------------
# Interval modules and their reversal.
# --------------------------------------------------------------------------

def is_interval_module(succ, n, S):
    """S is an interval module iff every outside key is above all of S or
    below all of S.  (S = V qualifies vacuously; S = 0 is excluded by callers.)
    """
    if S <= 0 or S >= (1 << n) - 1:
        return S == (1 << n) - 1
    outside = ((1 << n) - 1) ^ S
    a = 0
    while outside:
        bit = outside & -outside
        a = bit.bit_length() - 1
        outside ^= bit
        # Elements of S below a: b < a  <=> succ[b] has bit a.
        below = 0
        # Elements of S above a: a < b  <=> succ[a] has bit b.
        above = succ[a] & S
        s = S
        while s:
            bbit = s & -s
            b = bbit.bit_length() - 1
            s ^= bbit
            if succ[b] >> a & 1:
                below |= bbit
        if below != S and above != S:
            return False
    return True


def interval_modules(succ, n):
    """All interval modules, including the full vertex set (dual), excluding 0."""
    out = []
    for S in range(1, 1 << n):
        if is_interval_module(succ, n, S):
            out.append(S)
    return out


def reverse_interval(succ, n, S):
    """Reverse relations internal to the interval module S, keep all others.

    By Theorem 3 (and Lemma 1 in the note) the result is already a strict
    partial order: P = A (+) S (+) B, and only the middle factor is dualised.
    No transitive closure is needed.  We still assert closure cheaply below in
    the n <= 6 sanity check.
    """
    out = [0] * n
    for i in range(n):
        if S >> i & 1:
            for j in range(n):
                if i == j:
                    continue
                if S >> j & 1:
                    if succ[j] >> i & 1:       # j < i, flip to i < j
                        out[i] |= 1 << j
                elif succ[i] >> j & 1:
                    out[i] |= 1 << j
        else:
            out[i] = succ[i]                   # all cross/outside relations kept
    return tuple(out)


def _closure_ok(succ, n):
    """Cheap check that a bitmask relation is transitively closed."""
    for i in range(n):
        for j in range(n):
            if succ[i] >> j & 1:
                # i < j and j < k must give i < k
                if succ[j] & ~succ[i]:
                    return False
    return True


# --------------------------------------------------------------------------
# Isomorphism classes (no F computation) and the interval-reversal orbits.
# --------------------------------------------------------------------------

def enumerate_iso_classes(n, deadline=None):
    canon = make_refined_canon(n)
    start = canon((0,) * n)
    seen = {start}
    stack = [start]
    while stack:
        if deadline is not None and time.perf_counter() > deadline:
            raise TimeoutError("iso-class enumeration exceeded the cap")
        c = stack.pop()
        for i, j in incomparable_pairs(c, n):
            for s in (extend(c, i, j), extend(c, j, i)):
                cs = canon(s)
                if cs not in seen:
                    seen.add(cs)
                    stack.append(cs)
    return list(seen), canon


class UnionFind:
    def __init__(self, items):
        self.parent = {x: x for x in items}

    def find(self, x):
        while self.parent[x] != x:
            self.parent[x] = self.parent[self.parent[x]]
            x = self.parent[x]
        return x

    def union(self, a, b):
        ra, rb = self.find(a), self.find(b)
        if ra != rb:
            self.parent[ra] = rb


def interval_reversal_orbits(n, reps=None, canon=None, deadline=None):
    """Connected components of the Schreier graph of the generated group.

    Nodes are iso classes; edges are c -- canon(sigma_S(c)) for every interval
    module S (S = V included).  Each generator is an involution preserving F,
    so connected components are exactly the group orbits and F is constant on
    each component.  Returns (component representative map, class list).
    """
    if reps is None:
        reps, canon = enumerate_iso_classes(n, deadline)
    uf = UnionFind(reps)
    stats = Counter()
    for c in reps:
        if deadline is not None and time.perf_counter() > deadline:
            raise TimeoutError("interval-orbit construction exceeded the cap")
        for S in interval_modules(c, n):
            r = reverse_interval(c, n, S)
            stats["reversals"] += 1
            if not _closure_ok(r, n):
                raise AssertionError(("interval reversal not closed", n, c, S, r))
            cr = canon(r)
            stats["canon_calls"] += 1
            uf.union(c, cr)
    comps = {}
    for c in reps:
        comps.setdefault(uf.find(c), []).append(c)
    rep_of = {}
    classes = []
    for members in comps.values():
        members.sort()
        r = members[0]
        classes.append(members)
        for c in members:
            rep_of[c] = r
    return rep_of, classes, stats


# --------------------------------------------------------------------------
# Exact minimax DP on three quotients, with equal accounting.
# --------------------------------------------------------------------------

def solve_quotient(n, mode, orbit_rep=None, deadline=None):
    """mode: 'iso', 'iso+dual', or 'interval'.

    Returns (value, stats).  Distinct states are memoised by the quotient
    canonical form.  Every incomparable pair of the stored representative is
    still tried, so the recurrence is the exact one on the quotient.
    """
    canon = make_refined_canon(n)
    stats = Counter()

    if mode == "iso":
        def C(s):
            stats["canon_calls"] += 1
            return canon(s)
    elif mode == "iso+dual":
        def C(s):
            stats["canon_calls"] += 2
            c = canon(s)
            d = canon(dual(s, n))
            return c if c < d else d
    elif mode == "interval":
        def C(s):
            stats["canon_calls"] += 1
            return orbit_rep[canon(s)]
    else:
        raise ValueError(mode)

    states = {}

    def solve(c):
        if deadline is not None and time.perf_counter() > deadline:
            raise TimeoutError("DP exceeded the cap")
        if c in states:
            return states[c]
        ps = incomparable_pairs(c, n)
        if not ps:
            states[c] = 0
            return 0
        best = None
        for i, j in ps:
            stats["moves"] += 1
            stats["C_calls"] += 2
            a = C(extend(c, i, j))
            b = C(extend(c, j, i))
            v = 1 + max(solve(a), solve(b))
            if best is None or v < best:
                best = v
        states[c] = best
        return best

    t0 = time.perf_counter()
    value = solve(C((0,) * n))
    stats["seconds"] = time.perf_counter() - t0
    stats["states"] = len(states)
    return value, stats


