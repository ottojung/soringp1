def sanity_small(nmax=6):
    """Compare the direct interval reversal with the general closure-based
    reversal, and confirm interval reversals of low n stay posets."""
    try:
        from orientation_modules_probe import reverse_module, is_module
    except Exception as exc:  # pragma: no cover
        return [f"skipped (import failed: {exc})"]
    notes = []
    for n in range(1, nmax + 1):
        reps, _, _ = enumerate_iso_classes(n)[0], None, None
        for c in reps:
            for S in interval_modules(c, n):
                if not is_module(c, n, S):
                    raise AssertionError(("interval module not a module", n, c, S))
                direct = reverse_interval(c, n, S)
                closed = reverse_module(c, n, S)
                if closed is not None and direct != closed:
                    raise AssertionError(("reversal mismatch", n, c, S))
        notes.append(f"n={n}: ok")
    return notes


def orbit_size_histogram(classes):
    return dict(sorted(Counter(len(c) for c in classes).items()))


def successor_multiset_signature(c, n, rep_of, canon):
    """Multiset of unordered successor-class pairs, one per incomparable move."""
    out = []
    for i, j in incomparable_pairs(c, n):
        a = rep_of[canon(extend(c, i, j))]
        b = rep_of[canon(extend(c, j, i))]
        out.append(tuple(sorted((a, b))))
    out.sort()
    return tuple(out)


def check_transition_well_defined(n, classes, rep_of, canon, deadline=None):
    """Experiment: is the successor-class multiset constant across each class?

    This is NOT used by the DP (the DP is exact from value-invariance alone).
    It is a stronger necessary condition for quotient-level transitions and is
    provable directly from P = A (+) S (+) B; we only measure it here.
    """
    bad = []
    for cl in classes:
        if deadline is not None and time.perf_counter() > deadline:
            raise TimeoutError("transition check exceeded the cap")
        if len(cl) < 2:
            continue
        sigs = {successor_multiset_signature(c, n, rep_of, canon) for c in cl}
        if len(sigs) > 1:
            bad.append(cl)
    return bad


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--n7", action="store_true", help="run the n=7 checks")
    ap.add_argument("--n8", action="store_true", help="attempt n=8 under --cap")
    ap.add_argument("--cap", type=float, default=900.0,
                    help="wall-clock cap in seconds per phase (UNKNOWN on timeout)")
    ap.add_argument("--skip-sanity", action="store_true")
    ap.add_argument("--check-transitions", action="store_true",
                    help="check successor-class multiset well-definedness")
    ap.add_argument("--verify-f", action="store_true",
                    help="for n=8, compute F on every iso class and check classes")
    args = ap.parse_args()

    if not args.skip_sanity:
        print("Sanity: direct interval reversal == closure-based reversal, n<=6")
        for line in sanity_small(6):
            print("  ", line)

    if args.n7:
        print()
        print("=== n = 7: exhaustive exactness check ===")
        t0 = time.perf_counter()
        reps, canon = enumerate_iso_classes(7)
        t_enum = time.perf_counter() - t0
        vals = quotient_classes(7)
        print(f"iso classes: {len(reps)} (A000112 ref {A000112[7]}), "
              f"enumeration {t_enum:.2f}s")
        assert len(reps) == A000112[7]

        t0 = time.perf_counter()
        rep_of, classes, orb_stats = interval_reversal_orbits(
            7, reps=reps, canon=canon)
        t_orb = time.perf_counter() - t0
        print(f"interval reversals examined: {orb_stats['reversals']}, "
              f"canon calls: {orb_stats['canon_calls']}, "
              f"orbit construction {t_orb:.2f}s")
        print(f"iso x interval-reversal classes: {len(classes)}")
        print(f"orbit-size histogram: {orbit_size_histogram(classes)}")

        mixed = [cl for cl in classes if len({vals[c] for c in cl}) > 1]
        print(f"classes with non-constant F: {len(mixed)}")
        for cl in mixed:
            print("  COUNTEREXAMPLE:", [(c, vals[c]) for c in cl])

        if args.check_transitions:
            bad = check_transition_well_defined(7, classes, rep_of, canon)
            print(f"classes whose successor-class multiset is not well defined: "
                  f"{len(bad)}")
            for cl in bad[:3]:
                print("  transition counterexample:", cl[:6])

        # iso+dual baseline (counts classes, exact by the duality theorem)
        dual_classes = {}
        for c in reps:
            k = min(canon(c), canon(dual(c, 7)))
            dual_classes.setdefault(k, []).append(c)
        print(f"iso+dual classes: {len(dual_classes)}")
        print(f"iso+dual mixed-F classes: "
              f"{sum(1 for cl in dual_classes.values() if len({vals[c] for c in cl}) > 1)}")

        cost_table = []
        for mode in ("iso", "iso+dual", "interval"):
            try:
                val, st = solve_quotient(7, mode, orbit_rep=rep_of,
                                         deadline=time.perf_counter() + args.cap)
                cost_table.append((mode, val, st))
            except TimeoutError:
                cost_table.append((mode, "UNKNOWN", None))
        print("n | mode | S(n) | states | moves | C calls | canon calls | seconds")
        for mode, val, st in cost_table:
            if st is None:
                print(f"7 | {mode} | UNKNOWN under cap | - | - | - | - | -")
            else:
                print(f"7 | {mode} | {val} | {st['states']} | {st['moves']} "
                      f"| {st['C_calls']} | {st['canon_calls']} | "
                      f"{st['seconds']:.3f}")
        for mode, val, st in cost_table:
            if st is not None and val != KNOWN[7]:
                print(f"  !! {mode} returned {val}, expected {KNOWN[7]}")

    for n in ([8] if args.n8 else []):
        print()
        print(f"=== n = {n}: cost comparison under {args.cap:.0f}s cap per phase ===")
        deadline = time.perf_counter() + args.cap
        try:
            t0 = time.perf_counter()
            reps, canon = enumerate_iso_classes(n, deadline)
            t_enum = time.perf_counter() - t0
            print(f"iso classes: {len(reps)} (A000112 ref {A000112.get(n)}), "
                  f"enumeration {t_enum:.2f}s")
        except TimeoutError:
            print(f"UNKNOWN: iso-class enumeration exceeded {args.cap:.0f}s")
            continue

        try:
            t0 = time.perf_counter()
            rep_of, classes, orb_stats = interval_reversal_orbits(
                n, reps=reps, canon=canon, deadline=deadline)
            t_orb = time.perf_counter() - t0
            print(f"orbit construction: {t_orb:.2f}s, reversals "
                  f"{orb_stats['reversals']}, canon calls "
                  f"{orb_stats['canon_calls']}")
            print(f"iso x interval-reversal classes: {len(classes)}")
            print(f"orbit-size histogram: {orbit_size_histogram(classes)}")
            if args.check_transitions:
                bad = check_transition_well_defined(
                    n, classes, rep_of, canon,
                    deadline=time.perf_counter() + args.cap)
                print(f"classes whose successor-class multiset is not well "
                      f"defined: {len(bad)}")
            if args.verify_f:
                t0 = time.perf_counter()
                vals = quotient_classes(n)
                mixed = [cl for cl in classes
                         if len({vals[c] for c in cl}) > 1]
                print(f"F on all {len(vals)} iso classes in "
                      f"{time.perf_counter() - t0:.2f}s; "
                      f"classes with non-constant F: {len(mixed)}")
                for cl in mixed[:3]:
                    print("  COUNTEREXAMPLE:", [(c, vals[c]) for c in cl])
        except TimeoutError:
            print(f"UNKNOWN: orbit construction exceeded {args.cap:.0f}s")
            continue

        rows = []
        for mode in ("iso", "iso+dual", "interval"):
            try:
                val, st = solve_quotient(
                    n, mode, orbit_rep=rep_of,
                    deadline=time.perf_counter() + args.cap)
                rows.append((mode, val, st))
            except TimeoutError:
                rows.append((mode, "UNKNOWN", None))
        print(f"n | mode | S(n) | states | moves | C calls | canon calls | seconds")
        for mode, val, st in rows:
            if st is None:
                print(f"{n} | {mode} | UNKNOWN under cap | - | - | - | - | -")
            else:
                print(f"{n} | {mode} | {val} | {st['states']} | {st['moves']} "
                      f"| {st['C_calls']} | {st['canon_calls']} | "
                      f"{st['seconds']:.3f}")
        for mode, val, st in rows:
            if st is not None and val != KNOWN.get(n):
                print(f"  !! {mode} returned {val}, expected {KNOWN.get(n)}")


if __name__ == "__main__":
    main()
